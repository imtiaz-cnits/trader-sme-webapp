document.addEventListener('DOMContentLoaded', function() {
    // 1. Get Elements
    const modal = document.getElementById("chronoAddFolderModal");
    const btn = document.getElementById("chronoOpenFolderModalBtn"); 
    const span = document.getElementsByClassName("chrono-close-btn")[0]; 
    const form = document.getElementById("chronoAddFolderForm");
    const errorDiv = document.getElementById("chronoModalError");
    const folderList = document.getElementById("folderList"); // New: Where the folder will appear
    const saveBtn = document.getElementById('chronoSaveFolderBtn'); // New: For disabling

    // Function to dynamically add a new folder to the list
    function addNewFolderToUI(folder) {
        // Create a simple list item/div for the new folder
        const newFolderItem = document.createElement('div');
        // You might want to match the styling of your existing folder list items
        newFolderItem.innerHTML = `
            <div id="folder-${folder.id}" style="padding: 10px; border-bottom: 1px solid #eee; display: flex; justify-content: space-between;">
                <span>📂 **${folder.name}**</span>
                <small style="color: #666;">Created: ${new Date(folder.created_at).toLocaleDateString()}</small>
            </div>
        `;
        
        // Append it to the folder list
        if (folderList) {
            folderList.appendChild(newFolderItem);
        }
    }

    // 2. Add Event Listener to the Button (Open Modal)
    if (btn) {
        btn.onclick = function() {
            if (modal) {
                modal.style.display = "block";
                const folderNameInput = document.getElementById('chronoFolderName');
                // Clear state on open
                errorDiv.style.display = 'none';
                errorDiv.innerHTML = '';
                form.reset();
                if(folderNameInput) folderNameInput.focus();
            }
        };
    } else {
        console.error("Error: 'Add A Folder' button with ID 'chronoOpenFolderModalBtn' not found.");
    }
    
    // Function to close/reset the modal
    function closeAndResetModal() {
        if (modal) {
            modal.style.display = "none";
        }
        if (errorDiv) {
            errorDiv.style.display = 'none';
            errorDiv.innerHTML = '';
        }
        if (form) {
            form.reset();
        }
        if (saveBtn) {
            saveBtn.disabled = false;
            saveBtn.innerText = 'Save';
        }
    }

    // 3. Add Event Listener to the Close button
    if (span) {
        span.onclick = closeAndResetModal;
    }

    // 4. Close Modal when clicking outside
    window.onclick = function(event) {
        if (event.target == modal) {
            closeAndResetModal();
        }
    };
    
    // 5. AJAX Form Submission
    form.addEventListener('submit', function(e) {
        e.preventDefault(); // Prevent default form submission

        const folderName = document.getElementById('chronoFolderName').value.trim();
        const csrfToken = document.querySelector('input[name="_token"]').value;

        // Clear previous error messages
        errorDiv.style.display = 'none';
        errorDiv.innerHTML = '';
        saveBtn.disabled = true; // Disable button 
        saveBtn.innerText = 'Saving...'; // User feedback

        fetch('{{ route("folders.store") }}', { // **Important:** Use the route helper
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
                'X-Requested-With': 'XMLHttpRequest',
                'X-CSRF-TOKEN': csrfToken 
            },
            body: JSON.stringify({ name: folderName })
        })
        .then(response => {
            if (!response.ok) {
                // Handle 422 (Validation) and 500 (Server Error) responses
                return response.json().then(data => {
                    throw data; 
                });
            }
            return response.json();
        })
      .then(data => {
            // Success! (200 status)
            if (data.success) {
                
                // 1. Display the success message
                if (data.alert_message) {
                    // Use the alert from the server response
                    alert(data.alert_message); 
                } else {
                    // Or use a default alert
                    alert('Folder "' + data.folder.name + '" created successfully!');
                }
                
                // 2. Close the modal and reset the form immediately
                // (This is optional but cleans up the interface before the reload happens)
                closeAndResetModal(); 

                // 3. ✅ Reload the entire page to display the new folder
                window.location.reload(); 
            }
        })
        .catch(error => {
            // Handle errors
            errorDiv.style.display = 'block';
            
            if (error && error.errors && error.errors.name) {
                // Validation Errors (422)
                errorDiv.innerHTML = 'Error: ' + error.errors.name.join('<br>');
            } else if (error && error.message) {
                // Server Error (500)
                errorDiv.innerHTML = 'Error: ' + error.message;
            } else {
                errorDiv.innerHTML = 'An unknown network error occurred.';
                console.error('Fetch error:', error);
            }

            // Re-enable button and reset text
            saveBtn.disabled = false;
            saveBtn.innerText = 'Save';
        });
    });
});
